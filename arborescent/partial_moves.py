"""A2.3: auditable finite exploration of the *implemented* move subset.

The graph generated by F1, F2 and strict admissible F3' is a finite
presentation graph on a fixed weighted tree (no ring moves, no graph
growth/shrinkage). A replayable certificate proves graph reachability
under *these coded rewrites*, not topological isotopy or classification.

Source conventions: Bonahon--Siebenmann section 12.7.1 and 12.7.3.
"""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass

from .tangle_labels import (
    V4LabeledTree, tangle_flip_f1, tangle_flip_f2, tangle_flip_f3prime,
)
from .weighted_trees import enumerate_specs, to_weighted_tree


@dataclass(frozen=True)
class Move:
    """A precisely replayable implemented move, indexed by original bonds."""
    kind: str
    pivot: int = -1
    edge: str = ""
    side: str = ""

    def __post_init__(self) -> None:
        if self.kind not in ("F1", "F2", "F3prime"):
            raise ValueError("unsupported move type")
        if self.kind == "F1" and (self.pivot != -1 or self.edge or self.side):
            raise ValueError("F1 has no arguments")
        if self.kind == "F2" and (type(self.pivot) is not int
                                   or self.pivot < 0 or self.edge or self.side):
            raise ValueError("F2 takes only a pivot")
        if self.kind == "F3prime" and (
            type(self.pivot) is not int or self.pivot < 0
            or not self.edge.startswith("e")
            or self.side not in ("before", "after")
        ):
            raise ValueError("F3prime requires pivot, edge and side")


def apply(source: V4LabeledTree, move: Move) -> V4LabeledTree:
    """Apply one typed move or fail explicitly on invalid preconditions."""
    if move.kind == "F1":
        return tangle_flip_f1(source)
    if move.kind == "F2":
        return tangle_flip_f2(source, move.pivot)
    if move.kind == "F3prime":
        return tangle_flip_f3prime(
            source, move.pivot, move.edge, from_side=move.side
        )
    raise AssertionError("unreachable: Move validates types")


def _f2_pivots(source: V4LabeledTree) -> tuple[int, ...]:
    """Only the two parity types, not every redundant F2 pivot."""
    edges = source.tree.edges()
    if not edges:
        return (0,)
    neighbor_of_root = next(
        (v if u == 0 else u)
        for u, v in edges if u == 0 or v == 0
    )
    return (0, neighbor_of_root)


def successors(source: V4LabeledTree) -> tuple[tuple[Move, V4LabeledTree], ...]:
    """Enumerate one F1, two parity representatives of F2, and strict F3'."""
    moves = [Move("F1")]
    moves.extend(Move("F2", p) for p in _f2_pivots(source))
    for pivot, vertex in enumerate(source.tree.vertices):
        for edge in vertex.slots:
            if edge.startswith("e"):
                for side in ("before", "after"):
                    moves.append(Move("F3prime", pivot, edge, side))
    candidates = []
    seen = set()
    for move in moves:
        try:
            next_state = apply(source, move)
        except ValueError:
            continue
        # Dedup raw exact states only. Keep at least one replayable edge.
        if next_state not in seen:
            seen.add(next_state)
            candidates.append((move, next_state))
    return tuple(candidates)


@dataclass(frozen=True)
class Trace:
    """Shortest path *within the enumerated move graph*, with replay guards."""
    start: V4LabeledTree
    target: V4LabeledTree
    moves: tuple[Move, ...]

    def verify(self) -> bool:
        state = self.start
        for move in self.moves:
            state = apply(state, move)
        return state == self.target


@dataclass
class Orbit:
    """A bounded exact-state BFS with explicit completeness status."""
    start: V4LabeledTree
    predecessors: dict[V4LabeledTree, tuple[V4LabeledTree, Move] | None]
    complete: bool

    @property
    def size(self) -> int:
        return len(self.predecessors)

    def trace(self, target: V4LabeledTree) -> Trace:
        if target not in self.predecessors:
            raise ValueError("target has not been reached")
        cursor = target
        reverse = []
        while True:
            incoming = self.predecessors[cursor]
            if incoming is None:
                break
            parent, move = incoming
            reverse.append(move)
            cursor = parent
        if cursor != self.start:
            raise AssertionError("corrupt parent map")
        certificate = Trace(self.start, target, tuple(reversed(reverse)))
        if not certificate.verify():
            raise AssertionError("certificate replay failed")
        return certificate


def explore(start: V4LabeledTree, max_states: int = 4096) -> Orbit:
    """Search coded-rewrite reachability; NEVER treat cutoff as a full orbit."""
    if type(max_states) is not int or max_states < 1:
        raise ValueError("max_states must be positive")
    if not isinstance(start, V4LabeledTree):
        raise ValueError("start must be a V4-labelled weighted plane tree")
    predecessors: dict[V4LabeledTree, tuple[V4LabeledTree, Move] | None] = {
        start: None
    }
    queue = deque([start])
    while queue:
        source = queue.popleft()
        for move, target in successors(source):
            if target in predecessors:
                continue
            if len(predecessors) >= max_states:
                return Orbit(start, predecessors, complete=False)
            predecessors[target] = (source, move)
            queue.append(target)
    return Orbit(start, predecessors, complete=True)


def a1_has_applicable_f3prime(n: int, labels: tuple[int, ...] = (2, 3)) -> bool:
    """Is strict F3' nonvacuous on the existing A1 leaf-weight-only grammar?

    The answer is uniformly False: every nonzero sector is on a leaf,
    where a bond has the same sector on either side, so the strict
    move has no applicable internal edge.
    """
    if type(n) is not int or n < 1:
        raise ValueError("n must be at least one fork")
    for spec in enumerate_specs(n, labels):
        tree = to_weighted_tree(spec, labels)
        source = V4LabeledTree(tree, (("f0", 0),))
        if any(move.kind == "F3prime" for move, _ in successors(source)):
            return True
    return False
