"""A5.2e2b4c2e1 — one shared TWO-SIDED physical K-corner 3-ball.

The incoming-only and outgoing-only K-corner solids from earlier
milestones overlap in positive 3D volume at a shared knot vertex.
They CANNOT be unioned as disjoint tetrahedral material.

Instead clip ONE original exact-rational K-corner octahedron at BOTH
incident K-ray tips, exposing TWO nondegenerate disjoint triangularly
meshed 5-vertex cap disks. All 24 tetrahedra are generated by coning
the clipped convex boundary to the ORIGINAL K vertex. This is one
real embedded PL 3-ball, independently audited by exact 3D face/link,
convex tetrahedron-contact and rational volume verification.

This is a local shared K-corner core, NOT an attachment to neighboring
edge tubes, a whole-K ambient, source Conway slit or R+/- theorem.
"""
