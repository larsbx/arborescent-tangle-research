Vec=tuple[Fraction,Fraction,Fraction]
Tri=tuple[int,int,int]
Tet=tuple[int,int,int,int]
C=Fraction(3,4)     # Must exceed 1/2: otherwise tip cuts overlap/touch.

def _add(a:Vec,b:Vec)->Vec:
    return a[0]+b[0],a[1]+b[1],a[2]+b[2]

def _mul(a:Vec,t:Fraction)->Vec:
    return a[0]*t,a[1]*t,a[2]*t

def _interp(a:Vec,b:Vec,t:Fraction)->Vec:
    return _add(_mul(a,1-t),_mul(b,t))

def _clip_clean(poly:tuple[Vec,...],axis:int,sign:int)->tuple[Vec,...]:
    """Standard single-intersection-per-crossing rational polygon clipping."""
    if axis not in (0,1,2) or sign not in (-1,1):
        raise ValueError("invalid exact rational clipping halfspace")
    out=[]
    for i,q in enumerate(poly):
        p=poly[i-1]
        fp=sign*p[axis]-C
        fq=sign*q[axis]-C
        inside_p=fp<=0
        inside_q=fq<=0
        if inside_p!=inside_q:
            if fp==fq:
                raise ValueError("invalid cut crossing")
            out.append(_interp(p,q,fp/(fp-fq)))
        if inside_q:
            out.append(q)
    distinct=[]
    for v in out:
        if not distinct or v!=distinct[-1]:
            distinct.append(v)
    if len(distinct)>1 and distinct[0]==distinct[-1]:
        distinct.pop()
    return tuple(distinct)

def _frame_to_point(p:Point3,u:Vec,v:Vec,w:Vec,x:Vec)->Point3:
    base=_xyz(p)
    return Point3(*(base[i]+x[0]*u[i]+x[1]*v[i]+x[2]*w[i]
                    for i in range(3)))

def _geometry(original:RationalKCornerStar):
    if not isinstance(original,RationalKCornerStar):
        raise ValueError("typed genuine K-corner star required")
    original.audit()
    k_path=original.candidate.patches.strands.embedded_arcs()[original.arc]
    before,p,after=k_path[original.corner-1:original.corner+2]
    u,v,w,_,outgoing=_generators(before,p,after,original.radius)
    # The incoming cap always cuts +u. Outgoing cuts either +v
    # (bent source K) or -u (straight continuation).
    outgoing_axis,outgoing_sign=(1,1) if outgoing==3 else (0,-1)
    constraints=((0,1),(outgoing_axis,outgoing_sign))
    points=[p]
    index={p:0}
    def add(x:Vec)->int:
        vertex=_frame_to_point(p,u,v,w,x)
        if vertex not in index:
            index[vertex]=len(points)
            points.append(vertex)
        return index[vertex]
    tets=[]
    axes=((Fraction(1),0,0),(0,Fraction(1),0),(0,0,Fraction(1)))
    for sx,sy,sz in product((-1,1),repeat=3):
        polygon=(
            _mul(axes[0],Fraction(sx)),
            _mul(axes[1],Fraction(sy)),
            _mul(axes[2],Fraction(sz)),
        )
        for axis,sign in constraints:
            polygon=_clip_clean(polygon,axis,sign)
        if len(polygon)<3:
            raise ValueError("incompatible K tip cuts collapsed original facet")
        face_ids=tuple(add(vv) for vv in polygon)
        for j in range(1,len(face_ids)-1):
            # Physical Q3 signed tetrahedron orientation is checked
            # independently; cone apex is always original K vertex.
            tets.append(_oriented_tet(
                tuple(points),(0,face_ids[0],face_ids[j],face_ids[j+1])))
    caps=[]
    centers=[]
    # Positive cap coordinate frames in the same affine octahedron.
    for axis,sign in constraints:
        center=[Fraction(0)]*3
        center[axis]=C*sign
        center_id=add(tuple(center))
        transverse=[j for j in range(3) if j!=axis]
        # Four vertices of the diamond |x_trans1|+|x_trans2|=1-C.
        ring=[]
        directions=((transverse[0],1),(transverse[1],1),
                    (transverse[0],-1),(transverse[1],-1))
        # The physical cap normals must point OUT of the compact
        # convex 3-ball: +x incoming; +y or -x outgoing.
        if (axis,sign) in ((1,1),(0,-1)):
            directions=tuple(reversed(directions))
        for j,s in directions:
            a=list(center)
            a[j]=Fraction(s)*(1-C)
            ring.append(add(tuple(a)))
        faces=[]
        for i in range(4):
            face=(center_id,ring[i],ring[(i+1)%4])
            faces.append(face)
            tets.append(_oriented_tet(tuple(points),(0,*face)))
        centers.append(center_id)
        caps.append(tuple(faces))
    return tuple(points),tuple(tets),tuple(caps[0]),tuple(caps[1]),centers[0],centers[1]

@dataclass(frozen=True)
class DoublyTruncatedKCorner:
    """One physical, nonoverlapping source-K corner with TWO exposed disks."""
    original:RationalKCornerStar
    vertices:tuple[Point3,...]
    tetrahedra:tuple[Tet,...]
    incoming_faces:tuple[Tri,...]
    outgoing_faces:tuple[Tri,...]
    incoming_center:int
    outgoing_center:int
    status:Literal["DUAL_CAP_K_CORE_NOT_EDGE_GLUED"]=(
        "DUAL_CAP_K_CORE_NOT_EDGE_GLUED"
    )

    def __post_init__(self)->None:
        self.audit()

    def audit(self):
        if (not isinstance(self.original,RationalKCornerStar)
                or self.status!="DUAL_CAP_K_CORE_NOT_EDGE_GLUED"):
            raise ValueError("only source-unverified typed physical K cores")
        self.original.audit()
        expected=_geometry(self.original)
        if ((self.vertices,self.tetrahedra,self.incoming_faces,
              self.outgoing_faces,self.incoming_center,self.outgoing_center)
                !=expected):
            raise ValueError("physical dual-truncated K polyhedron was forged")
        stats=verify_connected_tetrahedral_ball(
            self.vertices,self.tetrahedra)
        if (stats.vertices!=15 or stats.tetrahedra!=24
                or stats.boundary_euler!=2 or stats.boundary_components!=1):
            raise ValueError("two-sided K core is not a valid 24-tet PL 3-ball")
        if (_cap_disk(self.vertices,self.incoming_faces,self.incoming_center)
                !=(5,8,4) or
            _cap_disk(self.vertices,self.outgoing_faces,self.outgoing_center)
                !=(5,8,4)):
            raise ValueError("both K caps must be genuine PL disks")
        incidence=Counter()
        for a,b,c,d in self.tetrahedra:
            for face in ((b,c,d),(a,d,c),(a,b,d),(a,c,b)):
                incidence[frozenset(face)]+=1
        for face in (*self.incoming_faces,*self.outgoing_faces):
            if incidence[frozenset(face)]!=1:
                raise ValueError("K cap triangle is buried or nonmanifold")
        if (set(i for face in self.incoming_faces for i in face) &
                set(i for face in self.outgoing_faces for i in face)):
            raise ValueError("incoming/outgoing K cap disks must be DISJOINT")
        # Independent signed outer normal check on every true exposed
        # 2-simplex. The two different K cap planes point along
        # the distinct incoming and outgoing source K rays.
        k_path=self.original.candidate.patches.strands.embedded_arcs()[
            self.original.arc]
        before,p,after=k_path[self.original.corner-1:
                               self.original.corner+2]
        for faces,normal_direction in (
            (self.incoming_faces,_minus(_xyz(before),_xyz(p))),
            (self.outgoing_faces,_minus(_xyz(after),_xyz(p)))
        ):
            for face in faces:
                a,b,c=(_xyz(self.vertices[i]) for i in face)
                if _dot(_cross(_minus(b,a),_minus(c,a)),
                        normal_direction)<=0:
                    raise ValueError("K cap exterior face normal is reversed")
        if (_link_cycle(self.tetrahedra,0,self.incoming_center)!=(4,4)
                or _link_cycle(self.tetrahedra,0,self.outgoing_center)!=(4,4)):
            raise ValueError("two true K core mesh rays require circular edge links")
        old=self.original.audit()
        # Each original octahedron tip removes exactly Δ/96 at C=3/4.
        # Two disjoint tips leave Δ*(4/3-1/48)=21Δ/16,
        # equivalently 63/64 of original octahedral volume.
        if stats.volume!=old.volume*Fraction(63,64):
            raise ValueError("two-sided K truncation exact volume mismatch")
        collisions=audit_embedded_tetrahedra(
            self.vertices,self.tetrahedra)
        if collisions.pair_count!=276:
            raise ValueError("not all 3D tetrahedron intersections checked")
        # Re-derive source-K subedge positions at ray fraction C*r.
        u,v,w,_,outgoing_axis=_generators(
            before,p,after,self.original.radius)
        expected_rays=(
            (self.incoming_center,u,before),
            (self.outgoing_center,v if outgoing_axis==3
             else tuple(-coordinate for coordinate in u),after),
        )
        for index,ray,terminal in expected_rays:
            expected=Point3(*(
                Fraction(getattr(p,k))+C*ray[i]
                for i,k in enumerate(("x","y","z"))))
            if self.vertices[index]!=expected:
                raise ValueError("two-sided K cap does not match exact ray")
            source=_minus(_xyz(terminal),_xyz(p))
            offset=_minus(_xyz(self.vertices[index]),_xyz(p))
            if _cross(source,offset)!=(0,0,0):
                raise ValueError("K cap center deviated from original K edge")
            axis=next(i for i,v in enumerate(source) if v!=0)
            t=offset[axis]/source[axis]
            if not Fraction(0)<t<Fraction(1):
                raise ValueError("K cap center not in proper original K subedge")
        return stats

    def require_global_source_ambient(self)->None:
        raise NotImplementedError(
            "UNVERIFIED_GEOMETRY: two disjoint physical K corner caps "
            "are not yet glued to adjacent K tubes or the global source "
            "ribbon/Conway ambient; no four-puncture slit or R+/-")

def truncate_both_k_rays(
    original:RationalKCornerStar
)->DoublyTruncatedKCorner:
    if not isinstance(original,RationalKCornerStar):
        raise ValueError("actual verified source-candidate K corner needed")
    return DoublyTruncatedKCorner(original,*_geometry(original))

def build_doubly_truncated_k_corner(
    atom,arc:int,corner:int,max_radius:Fraction=Fraction(1,4)
)->DoublyTruncatedKCorner:
    return truncate_both_k_rays(
        build_rational_k_corner_star(atom,arc,corner,max_radius))
