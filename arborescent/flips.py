"""Exact Bonahon--Siebenmann F1/F2 flip subgroup on weighted planar trees.

Source: Bonahon--Siebenmann, The Plumbing Calculus, sec. 12.3
(printed p. 146, PDF p. 157), and proof of Proposition 12.6
(printed p. 148, PDF p. 159). These moves preserve the *associated
arborescent pair up to pair isomorphism*, not boundary pointwise.

Not implemented: F3/F3'/F3'', rings, boundary/arithmetic moves,
exceptional canonical trees, or link/tangle isotopy classification.
"""
from __future__ import annotations

from collections import deque

from .weighted_trees import Vertex, WeightedPlaneTree, enumerate_specs, to_weighted_tree


def reverse_vertex(vertex: Vertex) -> Vertex:
    """Reverse cyclic order of bonds *and matching angular sectors*.

    If vertex slots are (s0,s1,...,sd-1) and sectors (a0,...,ad-1)
    with ai between si and s(i+1), then reflecting with anchor s0
    gives (s0,sd-1,...,s1), (ad-1,...,a0).
    """
    return Vertex(
        (vertex.slots[0],) + vertex.slots[:0:-1],
        vertex.sectors[::-1],
    )


def flip_vertices(tree: WeightedPlaneTree, indices: frozenset[int]) -> WeightedPlaneTree:
    """Reflect selected vertices, preserving bond IDs and all sector totals."""
    if any(type(i) is not int or i < 0 or i >= len(tree.vertices) for i in indices):
        raise ValueError("flip indices must be valid vertex indices")
    return WeightedPlaneTree(
        tuple(reverse_vertex(v) if i in indices else v
              for i, v in enumerate(tree.vertices))
    )


def bipartition(tree: WeightedPlaneTree, pivot: int = 0) -> tuple[frozenset[int], frozenset[int]]:
    """Return even- and odd-distance vertices from pivot in the tree."""
    if type(pivot) is not int or not 0 <= pivot < len(tree.vertices):
        raise ValueError("pivot vertex out of range")
    adjacency = [set() for _ in tree.vertices]
    for u, v in tree.edges():
        adjacency[u].add(v)
        adjacency[v].add(u)
    distances = {pivot: 0}
    queue = deque([pivot])
    while queue:
        i = queue.popleft()
        for j in adjacency[i]:
            if j not in distances:
                distances[j] = distances[i] + 1
                queue.append(j)
    # WeightedPlaneTree already verifies connectedness.
    assert len(distances) == len(tree.vertices)
    return (
        frozenset(v for v, d in distances.items() if d % 2 == 0),
        frozenset(v for v, d in distances.items() if d % 2 == 1),
    )


def flip_f1(tree: WeightedPlaneTree) -> WeightedPlaneTree:
    """(F1), reverse cyclic order at *every* vertex; pair-isomorphism move."""
    return flip_vertices(tree, frozenset(range(len(tree.vertices))))


def flip_f2(tree: WeightedPlaneTree, pivot: int) -> WeightedPlaneTree:
    """(F2), reverse at the pivot and each vertex at even graph distance."""
    even, _ = bipartition(tree, pivot)
    return flip_vertices(tree, even)


def parity_flip_representatives(tree: WeightedPlaneTree) -> tuple[WeightedPlaneTree, ...]:
    """Enumerate all at-most-four F1/F2 subgroup actions on a *fixed* tree.

    The action is generated by independent reflections of the two
    bipartition classes (V_even and V_odd), which commute and square
    to identity. F1 reflects both. On a one-vertex tree, one class is
    empty and only two action choices exist. No unbounded move search.
    """
    even, odd = bipartition(tree)
    return (
        tree,
        flip_vertices(tree, even),
        flip_vertices(tree, odd),
        flip_f1(tree),
    )


def flip_orbit_codes(tree: WeightedPlaneTree, marked_free_bond: str = "f0") -> frozenset[tuple]:
    """F1/F2 orbit modulo *marked plane-tree isomorphism* only."""
    return frozenset(
        variant.rooted_plane_code(marked_free_bond)
        for variant in parity_flip_representatives(tree)
    )


def flip_orbit_key(tree: WeightedPlaneTree, marked_free_bond: str = "f0") -> str:
    """Stable quotient key of the limited F1/F2 move subgroup."""
    return min(repr(code) for code in flip_orbit_codes(tree, marked_free_bond))


def flip_quotient_count(n: int, labels: tuple[int, ...] = (2, 3)) -> int:
    """Exhaustive small-n count for the *restricted* flip subgroup only.

    n is the number of syntax fork nodes. A topological count is NOT
    asserted. n=0 has no marked root free bond in the grammar.
    """
    if type(n) is not int or n < 1:
        raise ValueError("n must be at least one fork")
    return len({
        flip_orbit_key(to_weighted_tree(spec, labels))
        for spec in enumerate_specs(n, labels)
    })
